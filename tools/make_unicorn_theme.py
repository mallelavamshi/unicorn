"""Generates the Unicorn keyboard look (rounded keys with a hairline shadow) for the LXX light/dark themes.

Writes drawables + colors into app/src/main/res and repoints the LXX theme styles to them. Re-runnable.
"""
import re
import sys
from pathlib import Path

RES = Path(sys.argv[1]) / "app" / "src" / "main" / "res"
DRAWABLE = RES / "drawable"
RADIUS = "8dp"

PALETTES = {
    "light": {
        "keyboard_bg": "#D2D4DA",
        "key": "#FFFFFF",
        "key_pressed": "#C6C9D0",
        "functional": "#ABB1BC",
        "functional_pressed": "#FFFFFF",
        "shadow": "#808A8E96",
        "action": "#7430A4",
        "action_pressed": "#5B2385",
        "toggle_on": "#E7DAF5",
    },
    "dark": {
        "keyboard_bg": "#1B1B1E",
        "key": "#434348",
        "key_pressed": "#5C5C63",
        "functional": "#2B2B2F",
        "functional_pressed": "#434348",
        "shadow": "#CC000000",
        "action": "#7430A4",
        "action_pressed": "#8E4CC2",
        "toggle_on": "#3D2A52",
    },
}

HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_unicorn_theme.py -->\n'


def shape(name, fill, shadow):
    return HEADER + f"""<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:top="1dp">
        <shape android:shape="rectangle">
            <corners android:radius="{RADIUS}" />
            <solid android:color="{shadow}" />
        </shape>
    </item>
    <item android:bottom="1dp">
        <shape android:shape="rectangle">
            <corners android:radius="{RADIUS}" />
            <solid android:color="{fill}" />
        </shape>
    </item>
</layer-list>
"""


def selector(theme, normal, pressed):
    t = theme
    return HEADER + f"""<selector xmlns:android="http://schemas.android.com/apk/res/android">
    <!-- Action keys (enter, go, send, ...) -->
    <item android:state_active="true" android:state_pressed="true" android:drawable="@drawable/unicorn_key_action_pressed_{t}" />
    <item android:state_active="true" android:drawable="@drawable/unicorn_key_action_{t}" />
    <!-- Toggle keys (shift lock) -->
    <item android:state_checkable="true" android:state_checked="true" android:state_pressed="true" android:drawable="@drawable/unicorn_key_{pressed}_{t}" />
    <item android:state_checkable="true" android:state_pressed="true" android:drawable="@drawable/unicorn_key_{pressed}_{t}" />
    <item android:state_checkable="true" android:state_checked="true" android:drawable="@drawable/unicorn_key_toggle_on_{t}" />
    <item android:state_checkable="true" android:drawable="@drawable/unicorn_key_{normal}_{t}" />
    <!-- Empty keys -->
    <item android:state_empty="true" android:state_pressed="true" android:drawable="@drawable/unicorn_key_{pressed}_{t}" />
    <item android:state_empty="true" android:drawable="@android:color/transparent" />
    <!-- Normal -->
    <item android:state_pressed="true" android:drawable="@drawable/unicorn_key_{pressed}_{t}" />
    <item android:drawable="@drawable/unicorn_key_{normal}_{t}" />
</selector>
"""


for theme, p in PALETTES.items():
    for kind in ["key", "key_pressed", "functional", "functional_pressed", "action", "action_pressed", "toggle_on"]:
        name = {"key": "letter", "key_pressed": "letter_pressed"}.get(kind, kind)
        (DRAWABLE / f"unicorn_key_{name}_{theme}.xml").write_text(shape(name, p[kind], p["shadow"]), encoding="utf-8")
    (DRAWABLE / f"unicorn_key_bg_{theme}.xml").write_text(selector(theme, "letter", "letter_pressed"), encoding="utf-8")
    (DRAWABLE / f"unicorn_key_functional_bg_{theme}.xml").write_text(
        selector(theme, "functional", "functional_pressed"), encoding="utf-8")
    (DRAWABLE / f"unicorn_keyboard_background_{theme}.xml").write_text(HEADER + f"""<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="{p['keyboard_bg']}" />
</shape>
""", encoding="utf-8")

    # Point the LXX theme at the Unicorn drawables
    themes = RES / "values" / f"themes-lxx-{theme}.xml"
    s = themes.read_text(encoding="utf-8")
    s = re.sub(rf'@drawable/keyboard_background_lxx_{theme}\b', f"@drawable/unicorn_keyboard_background_{theme}", s)
    s = re.sub(rf'@drawable/btn_keyboard_key_lxx_{theme}\b', f"@drawable/unicorn_key_bg_{theme}", s)
    s = re.sub(rf'@drawable/btn_keyboard_key_functional_lxx_{theme}\b', f"@drawable/unicorn_key_functional_bg_{theme}", s)
    s = re.sub(rf'@drawable/btn_keyboard_spacebar_lxx_{theme}\b', f"@drawable/unicorn_key_bg_{theme}", s)
    themes.write_text(s, encoding="utf-8", newline="\n")

# Action keys sit on purple, so the light theme uses the white (dark-theme) action icons
icons = RES / "values" / "keyboard-icons-lxx-light.xml"
s = icons.read_text(encoding="utf-8")
for icon in ["return", "go", "search", "send", "next", "done", "previous"]:
    s = s.replace(f"@drawable/sym_keyboard_{icon}_lxx_light", f"@drawable/sym_keyboard_{icon}_lxx_dark")
icons.write_text(s, encoding="utf-8", newline="\n")

# Accent colors: teal -> Unicorn purple, crisper text
colors = RES / "values" / "colors.xml"
s = colors.read_text(encoding="utf-8")
replacements = {
    "key_text_color_lxx_light": "#111114",
    "key_functional_text_color_lxx_light": "#111114",
    "key_text_inactive_color_lxx_light": "#8E8E93",
    "key_hint_letter_color_lxx_light": "#8E8E93",
    "language_on_spacebar_text_color_lxx_light": "#8E8E93",
    "highlight_color_lxx_light": "#7430A4",
    "auto_correct_color_lxx_light": "#7430A4",
    "typed_word_color_lxx_light": "#111114",
    "suggested_word_color_lxx_light": "#3A3A3C",
    "gesture_trail_color_lxx_light": "#9B5DE5",
    "sliding_key_input_preview_color_lxx_light": "#B39B5DE5",
    "key_background_lxx_light": "#FFFFFF",
    "key_background_pressed_lxx_light": "#C6C9D0",
    "suggested_word_background_selected_lxx_light": "#267430A4",
    "key_text_color_lxx_dark": "#F5F5F7",
    "key_functional_text_color_lxx_dark": "#F5F5F7",
    "highlight_color_lxx_dark": "#B98AE8",
    "auto_correct_color_lxx_dark": "#D2B4F2",
    "gesture_trail_color_lxx_dark": "#B98AE8",
    "sliding_key_input_preview_color_lxx_dark": "#B3B98AE8",
    "key_background_lxx_dark": "#434348",
    "suggested_word_background_selected_lxx_dark": "#40B98AE8",
}
for name, value in replacements.items():
    s, n = re.subn(rf'(<color name="{name}">)#[0-9A-Fa-f]+(</color>)', rf"\g<1>{value}\g<2>", s)
    assert n == 1, name
colors.write_text(s, encoding="utf-8", newline="\n")
print("unicorn theme generated")
