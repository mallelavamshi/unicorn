"""Generates app/src/main/jni/Android.mk from AOSP LatinIME's native/jni/Android.bp source list."""
import re
import sys
from pathlib import Path

bp_path, out_path = Path(sys.argv[1]), Path(sys.argv[2])
bp = bp_path.read_text(encoding="utf-8")
core = re.findall(r'"([^"]+\.cpp)"', re.search(r'name: "LATIN_IME_CORE_SRC_FILES",\s*srcs: \[(.*?)\]', bp, re.S).group(1))
lib = re.search(r'cc_library \{\s*name: "libjni_latinime",(.*?)\n\}', bp, re.S).group(1)
jni = re.findall(r'"([^"]+\.cpp)"', re.search(r'\n    srcs: \[(.*?)\]', lib, re.S).group(1))

lines = [
    "# Copyright (C) 2011 The Android Open Source Project",
    "# Licensed under the Apache License, Version 2.0.",
    "# Generated by tools/gen_android_mk.py from AOSP LatinIME native/jni/Android.bp for ndk-build.",
    "",
    "LOCAL_PATH := $(call my-dir)",
    "",
    "include $(CLEAR_VARS)",
    "",
    "LOCAL_MODULE := jni_latinime",
    "LOCAL_C_INCLUDES += $(LOCAL_PATH)/src",
    "LOCAL_CFLAGS += -Wall -Wextra -Wno-unused-parameter -Wno-unused-function -Wno-format-nonliteral",
    "LOCAL_CPPFLAGS += -std=c++17 -fno-exceptions -fno-rtti",
    "LOCAL_LDLIBS := -llog",
    "LOCAL_LDFLAGS += -Wl,-z,max-page-size=16384",
    "",
    "LOCAL_SRC_FILES := \\",
]
lines += [f"    {f} \\" for f in jni + core]
lines += ["", "include $(BUILD_SHARED_LIBRARY)", ""]
out_path.write_text("\n".join(lines), encoding="utf-8", newline="\n")
print(f"{len(jni) + len(core)} sources")
