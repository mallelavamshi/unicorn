"""Generates keyboard themes from tools/keyboard_themes.json.

Writes key drawables and styles for every non-builtin theme (ids 10+), each inheriting the engine's LXX light or dark
style so layouts and icons stay correct, plus ai/unicorn/keyboard/KeyboardPalettes.kt for the Unicorn toolbar, the
navigation bar strip and the app's theme picker. Re-runnable.
"""
import json
import sys
from pathlib import Path

ROOT = Path(sys.argv[1])
SPEC = json.loads((ROOT / "tools" / "keyboard_themes.json").read_text(encoding="utf-8"))
RES = ROOT / "app" / "src" / "main" / "res"
DRAWABLE = RES / "drawable"
KOTLIN = ROOT / "app" / "src" / "main" / "kotlin" / "ai" / "unicorn" / "keyboard" / "KeyboardPalettes.kt"
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/make_keyboard_themes.py from tools/keyboard_themes.json -->\n'


def key_shape(fill, shadow, radius):
    return HEADER + f"""<layer-list xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:top="1dp">
        <shape android:shape="rectangle"><corners android:radius="{radius}dp" /><solid android:color="{shadow}" /></shape>
    </item>
    <item android:bottom="1dp">
        <shape android:shape="rectangle"><corners android:radius="{radius}dp" /><solid android:color="{fill}" /></shape>
    </item>
</layer-list>
"""


def selector(prefix, normal, pressed):
    return HEADER + f"""<selector xmlns:android="http://schemas.android.com/apk/res/android">
    <item android:state_active="true" android:state_pressed="true" android:drawable="@drawable/{prefix}_action_pressed" />
    <item android:state_active="true" android:drawable="@drawable/{prefix}_action" />
    <item android:state_checkable="true" android:state_checked="true" android:state_pressed="true" android:drawable="@drawable/{prefix}_{pressed}" />
    <item android:state_checkable="true" android:state_pressed="true" android:drawable="@drawable/{prefix}_functional_pressed" />
    <item android:state_checkable="true" android:state_checked="true" android:drawable="@drawable/{prefix}_toggle_on" />
    <item android:state_checkable="true" android:drawable="@drawable/{prefix}_functional" />
    <item android:state_empty="true" android:state_pressed="true" android:drawable="@drawable/{prefix}_{pressed}" />
    <item android:state_empty="true" android:drawable="@android:color/transparent" />
    <item android:state_pressed="true" android:drawable="@drawable/{prefix}_{pressed}" />
    <item android:drawable="@drawable/{prefix}_{normal}" />
</selector>
"""


def board(t):
    if "backgroundEnd" in t:
        return HEADER + f"""<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <gradient android:angle="270" android:startColor="{t['background']}" android:endColor="{t['backgroundEnd']}" />
</shape>
"""
    return HEADER + f"""<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">
    <solid android:color="{t['background']}" />
</shape>
"""


styles = []
for t in SPEC["themes"]:
    if t.get("builtin"):
        continue
    k = t["key"]
    p = f"unicorn_t_{k}"
    for kind, color in [
        ("letter", t["letter"]), ("letter_pressed", t["letterPressed"]), ("functional", t["functional"]),
        ("functional_pressed", t["functionalPressed"]), ("action", t["action"]), ("action_pressed", t["actionPressed"]),
        ("toggle_on", t["toggleOn"]),
    ]:
        (DRAWABLE / f"{p}_{kind}.xml").write_text(key_shape(color, t["shadow"], t["radius"]), encoding="utf-8")
    (DRAWABLE / f"{p}_key_bg.xml").write_text(selector(p, "letter", "letter_pressed"), encoding="utf-8")
    (DRAWABLE / f"{p}_functional_bg.xml").write_text(selector(p, "functional", "functional_pressed"), encoding="utf-8")
    (DRAWABLE / f"{p}_board.xml").write_text(board(t), encoding="utf-8")
    (DRAWABLE / f"{p}_shift_shifted.xml").write_text(HEADER + f"""<bitmap xmlns:android="http://schemas.android.com/apk/res/android"
    android:src="@drawable/sym_keyboard_shift_locked_lxx_light"
    android:tint="{t.get('shiftActive', t['accent'])}" />
""", encoding="utf-8")

    base = "LXX_Light" if t["base"] == "light" else "LXX_Dark"
    name = "Unicorn_" + "".join(part.capitalize() for part in k.split("_"))
    view_items = f"""        <item name="android:background">@drawable/{p}_board</item>
        <item name="keyBackground">@drawable/{p}_key_bg</item>
        <item name="functionalKeyBackground">@drawable/{p}_functional_bg</item>
        <item name="spacebarBackground">@drawable/{p}_key_bg</item>
        <item name="keyTextColor">{t['text']}</item>
        <item name="keyTextInactivatedColor">{t['secondaryText']}</item>
        <item name="functionalTextColor">{t['text']}</item>
        <item name="keyHintLetterColor">{t['secondaryText']}</item>
        <item name="keyHintLabelColor">{t['secondaryText']}</item>
        <item name="keyShiftedLetterHintInactivatedColor">{t['secondaryText']}</item>
        <item name="keyShiftedLetterHintActivatedColor">{t['text']}</item>
        <item name="keyPreviewTextColor">{t['text'] if t['base'] == 'dark' else '#000000'}</item>
"""
    styles.append(f"""    <style name="KeyboardTheme.{name}" parent="KeyboardTheme.{base}">
        <item name="iconShiftKeyShifted">@drawable/{p}_shift_shifted</item>
        <item name="keyboardViewStyle">@style/KeyboardView.{name}</item>
        <item name="mainKeyboardViewStyle">@style/MainKeyboardView.{name}</item>
        <item name="emojiPalettesViewStyle">@style/EmojiPalettesView.{name}</item>
        <item name="suggestionStripViewStyle">@style/SuggestionStripView.{name}</item>
        <item name="suggestionWordStyle">@style/SuggestionWord.{name}</item>
    </style>
    <style name="KeyboardView.{name}" parent="KeyboardView.{base}">
{view_items}    </style>
    <style name="MainKeyboardView.{name}" parent="MainKeyboardView.{base}">
{view_items}        <item name="gestureTrailColor">{t['accent']}</item>
        <item name="slidingKeyInputPreviewColor">{t['accent']}</item>
        <item name="gestureFloatingPreviewTextColor">{t['accent']}</item>
        <item name="languageOnSpacebarTextColor">{t['secondaryText']}</item>
    </style>
    <style name="EmojiPalettesView.{name}" parent="EmojiPalettesView.{base}">
{view_items}        <item name="categoryPageIndicatorColor">{t['accent']}</item>
    </style>
    <style name="SuggestionStripView.{name}" parent="SuggestionStripView.{base}">
        <item name="android:background">{t['background']}</item>
        <item name="colorValidTypedWord">{t['text']}</item>
        <item name="colorTypedWord">{t['text']}</item>
        <item name="colorAutoCorrect">{t['accent']}</item>
        <item name="colorSuggested">{t['text']}</item>
    </style>
    <style name="SuggestionWord.{name}" parent="SuggestionWord.{base}">
        <item name="android:textColor">{t['text']}</item>
    </style>
""")

(RES / "values" / "themes-unicorn-generated.xml").write_text(
    HEADER + "<resources>\n" + "\n".join(styles) + "</resources>\n", encoding="utf-8")


def argb(c):
    c = c.lstrip("#")
    return "0x" + (c if len(c) == 8 else "FF" + c).upper()


entries = []
for t in SPEC["themes"]:
    style = "null" if t.get("builtin") else "R.style.KeyboardTheme_Unicorn_" + "".join(p.capitalize() for p in t["key"].split("_"))
    entries.append(
        f'        KeyboardPalette({t["id"]}, "{t["name"]}", isDark = {str(t["base"] == "dark").lower()}, '
        f'background = {argb(t["background"])}.toInt(), backgroundEnd = {argb(t.get("backgroundEnd", t["background"]))}.toInt(), '
        f'letter = {argb(t["letter"])}.toInt(), functional = {argb(t["functional"])}.toInt(), action = {argb(t["action"])}.toInt(), '
        f'text = {argb(t["text"])}.toInt(), secondaryText = {argb(t["secondaryText"])}.toInt(), '
        f'accent = {argb(t["accent"])}.toInt(), chip = {argb(t["chip"])}.toInt(), styleRes = {style}),'
    )

